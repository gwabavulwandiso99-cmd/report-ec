"""Conversation states and the transitions allowed between them.

Every state change in the chatbot goes through `check_transition`, so a bug
can't move a resident into a step that makes no sense (for example from the
language menu straight to "report submitted").
"""
from enum import Enum


class State(str, Enum):
    LANGUAGE_SELECTION = "LANGUAGE_SELECTION"
    MAIN_MENU = "MAIN_MENU"
    RESUME_PROMPT = "RESUME_PROMPT"
    # Reporting
    AWAITING_DESCRIPTION = "AWAITING_DESCRIPTION"
    AWAITING_CATEGORY_CLARIFICATION = "AWAITING_CATEGORY_CLARIFICATION"
    AWAITING_LOCATION = "AWAITING_LOCATION"
    AWAITING_WARD = "AWAITING_WARD"
    AWAITING_EVIDENCE = "AWAITING_EVIDENCE"
    AWAITING_CONFIRMATION = "AWAITING_CONFIRMATION"   # summary shown, waiting for submit/edit/cancel
    EDIT_MENU = "EDIT_MENU"
    SUBMITTING = "SUBMITTING"
    SUBMISSION_FAILED = "SUBMISSION_FAILED"
    REPORT_SUBMITTED = "REPORT_SUBMITTED"
    # Status lookup
    AWAITING_REFERENCE = "AWAITING_REFERENCE"
    # Community verification
    AWAITING_VERIFICATION_REFERENCE = "AWAITING_VERIFICATION_REFERENCE"
    AWAITING_VERIFICATION_RESPONSE = "AWAITING_VERIFICATION_RESPONSE"
    AWAITING_VERIFICATION_DETAILS = "AWAITING_VERIFICATION_DETAILS"
    VERIFICATION_FAILED = "VERIFICATION_FAILED"
    CANCELLED = "CANCELLED"


S = State

# States you can always jump to with a command (menu, cancel, restart, language)
GLOBAL_TARGETS = {S.MAIN_MENU, S.CANCELLED, S.LANGUAGE_SELECTION}

# States that belong to an unfinished report (used for "resume" and "back")
REPORT_STATES = {
    S.AWAITING_DESCRIPTION, S.AWAITING_CATEGORY_CLARIFICATION, S.AWAITING_LOCATION,
    S.AWAITING_WARD, S.AWAITING_EVIDENCE, S.AWAITING_CONFIRMATION, S.EDIT_MENU,
    S.SUBMISSION_FAILED,
}

ALLOWED = {
    S.LANGUAGE_SELECTION: REPORT_STATES | {S.MAIN_MENU, S.RESUME_PROMPT, S.AWAITING_REFERENCE,
                                           S.AWAITING_VERIFICATION_REFERENCE, S.AWAITING_VERIFICATION_RESPONSE,
                                           S.AWAITING_VERIFICATION_DETAILS},
    S.MAIN_MENU: {S.AWAITING_DESCRIPTION, S.AWAITING_REFERENCE, S.AWAITING_VERIFICATION_REFERENCE,
                  S.RESUME_PROMPT},
    S.RESUME_PROMPT: REPORT_STATES | {S.AWAITING_DESCRIPTION},
    S.AWAITING_DESCRIPTION: {S.AWAITING_CATEGORY_CLARIFICATION, S.AWAITING_LOCATION, S.AWAITING_WARD,
                             S.AWAITING_EVIDENCE, S.AWAITING_CONFIRMATION},
    S.AWAITING_CATEGORY_CLARIFICATION: {S.AWAITING_LOCATION, S.AWAITING_WARD, S.AWAITING_EVIDENCE,
                                        S.AWAITING_CONFIRMATION, S.AWAITING_DESCRIPTION},
    S.AWAITING_LOCATION: {S.AWAITING_WARD, S.AWAITING_EVIDENCE, S.AWAITING_CONFIRMATION,
                          S.AWAITING_DESCRIPTION, S.AWAITING_CATEGORY_CLARIFICATION},
    S.AWAITING_WARD: {S.AWAITING_EVIDENCE, S.AWAITING_CONFIRMATION, S.AWAITING_LOCATION},
    S.AWAITING_EVIDENCE: {S.AWAITING_CONFIRMATION, S.AWAITING_WARD},
    S.AWAITING_CONFIRMATION: {S.SUBMITTING, S.EDIT_MENU, S.AWAITING_EVIDENCE, S.AWAITING_WARD},
    S.EDIT_MENU: {S.AWAITING_DESCRIPTION, S.AWAITING_LOCATION, S.AWAITING_WARD, S.AWAITING_EVIDENCE,
                  S.AWAITING_CATEGORY_CLARIFICATION, S.AWAITING_CONFIRMATION},
    S.SUBMITTING: {S.REPORT_SUBMITTED, S.SUBMISSION_FAILED},
    S.SUBMISSION_FAILED: {S.SUBMITTING, S.EDIT_MENU, S.AWAITING_CONFIRMATION},
    S.REPORT_SUBMITTED: set(),
    S.AWAITING_REFERENCE: set(),
    S.AWAITING_VERIFICATION_REFERENCE: {S.AWAITING_VERIFICATION_RESPONSE},
    S.AWAITING_VERIFICATION_RESPONSE: {S.AWAITING_VERIFICATION_DETAILS, S.AWAITING_VERIFICATION_REFERENCE},
    S.AWAITING_VERIFICATION_DETAILS: {S.VERIFICATION_FAILED, S.AWAITING_VERIFICATION_RESPONSE},
    S.VERIFICATION_FAILED: {S.AWAITING_VERIFICATION_DETAILS},
    S.CANCELLED: set(),
}


class InvalidTransition(Exception):
    pass


def check_transition(current: State, new: State) -> None:
    if new == current or new in GLOBAL_TARGETS:
        return
    if new not in ALLOWED.get(current, set()):
        raise InvalidTransition(f"{current.value} -> {new.value} is not allowed")
